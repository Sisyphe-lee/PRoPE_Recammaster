## 使用新的temporal index RoPE功能进行5帧降采样训练
## 这个实验将使用真实的时序索引而不是连续的索引

# 训练参数说明：
# -F 5: 从每半中采样5帧，总共10帧
# -T: 启用真实时序索引，RoPE使用实际帧位置而不是[0,1,2,3...]
# -b 2: batch size为2
# -c "2,3,4,5,6,7": 使用GPU 2-7
# -g 42: 随机种子42
# -w Exp07k: wandb实验名称

bash ./scripts/train.sh -F 5 -T -b 8 -c "2,3,4,5,6,7" -g 42 -w Exp09a